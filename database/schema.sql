-- Grupos que o usuário pode se enquadrar: cliente do clube, cliente eventual e funcionário

CREATE TABLE grupo (
                       id_grupo   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nome       VARCHAR(60)  NOT NULL UNIQUE,
                       descricao  VARCHAR(200)
);

-- Usuários: ADMIN cadastra, RESPONDENTE responde.
CREATE TABLE usuario (
                         id_usuario  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome        VARCHAR(100) NOT NULL,
                         email       VARCHAR(120) NOT NULL UNIQUE,
                         papel       VARCHAR(12)  NOT NULL DEFAULT 'RESPONDENTE',
                         id_grupo    INT REFERENCES grupo (id_grupo),
                         CONSTRAINT ck_usuario_papel  CHECK (papel IN ('ADMIN', 'RESPONDENTE')),
                         CONSTRAINT ck_usuario_email  CHECK (email LIKE '%_@_%._%'),
                         CONSTRAINT ck_usuario_grupo  CHECK (papel = 'ADMIN' OR id_grupo IS NOT NULL) -- ADM n precisa ter grupo
);

-- Temas
CREATE TABLE tema (
                      id_tema    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      nome       VARCHAR(60)  NOT NULL UNIQUE,
                      descricao  VARCHAR(200)
);

-- Tipos de questão
CREATE TABLE tipo_questao (
                              id_tipo    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              codigo     VARCHAR(20)  NOT NULL UNIQUE,
                              descricao  VARCHAR(100) NOT NULL,
                              CONSTRAINT ck_tipo_codigo CHECK (codigo IN ('ESCALA', 'MULTIPLA_ESCOLHA', 'TEXTO_LIVRE'))
);