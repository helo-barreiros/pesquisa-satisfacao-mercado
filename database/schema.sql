-- Grupos que o usuário pode se enquadrar: cliente do clube, cliente eventual e funcionário

CREATE TABLE grupo (
                       id_grupo   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nome       VARCHAR(60)  NOT NULL UNIQUE,
                       descricao  VARCHAR(200)
);

-- Usuários: ADMIN cadastra, RESPONDENTE responde.
CREATE TABLE usuario (
                         id_usuario  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome        VARCHAR(100) NOT NULL,
                         email       VARCHAR(120) NOT NULL UNIQUE,
                         papel       VARCHAR(12)  NOT NULL DEFAULT 'RESPONDENTE',
                         id_grupo    INT REFERENCES grupo (id_grupo),
                         CONSTRAINT ck_usuario_papel  CHECK (papel IN ('ADMIN', 'RESPONDENTE')),
                         CONSTRAINT ck_usuario_email  CHECK (email LIKE '%_@_%._%'),
                         CONSTRAINT ck_usuario_grupo  CHECK (papel = 'ADMIN' OR id_grupo IS NOT NULL) -- ADM n precisa ter grupo
);

-- Temas
CREATE TABLE tema (
                      id_tema    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      nome       VARCHAR(60)  NOT NULL UNIQUE,
                      descricao  VARCHAR(200)
);

-- Tipos de questão
CREATE TABLE tipo_questao (
                              id_tipo    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              codigo     VARCHAR(20)  NOT NULL UNIQUE,
                              descricao  VARCHAR(100) NOT NULL,
                              CONSTRAINT ck_tipo_codigo CHECK (codigo IN ('ESCALA', 'MULTIPLA_ESCOLHA', 'TEXTO_LIVRE'))
);

-- Questões, escala de 1 a 5
CREATE TABLE questao (
                         id_questao    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         enunciado     VARCHAR(300) NOT NULL,
                         id_tipo       INT NOT NULL REFERENCES tipo_questao (id_tipo),
                         id_tema       INT NOT NULL REFERENCES tema (id_tema),
                         ativa         BOOLEAN   NOT NULL DEFAULT TRUE,
                         data_criacao  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         CONSTRAINT ck_questao_enunciado CHECK (length(trim(enunciado)) >= 5)
);

-- Alternativas das questões de múltipla escolha
CREATE TABLE alternativa (
                             id_alternativa  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             id_questao      INT NOT NULL REFERENCES questao (id_questao) ON DELETE CASCADE,
                             ordem           SMALLINT     NOT NULL,
                             texto           VARCHAR(150) NOT NULL,
                             CONSTRAINT ck_alternativa_ordem CHECK (ordem > 0),
                             CONSTRAINT uq_alternativa_ordem UNIQUE (id_questao, ordem),
                             CONSTRAINT uq_alternativa_questao UNIQUE (id_alternativa, id_questao) -- garante que alternativa pertence a questão
);

-- Pesquisas "avaliações"
CREATE TABLE pesquisa (
                          id_pesquisa  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          titulo       VARCHAR(120) NOT NULL,
                          descricao    VARCHAR(500),
                          inicio       TIMESTAMP NOT NULL,
                          fim          TIMESTAMP NOT NULL,
                          anonima      BOOLEAN   NOT NULL DEFAULT TRUE,
                          criada_por   INT NOT NULL REFERENCES usuario (id_usuario),
                          CONSTRAINT ck_pesquisa_periodo CHECK (fim > inicio),
                          CONSTRAINT uq_pesquisa_titulo  UNIQUE (titulo)
);

-- Compõe
CREATE TABLE pesquisa_questao (
                                  id_pesquisa  INT NOT NULL REFERENCES pesquisa (id_pesquisa) ON DELETE CASCADE,
                                  id_questao   INT NOT NULL REFERENCES questao (id_questao),
                                  ordem        SMALLINT NOT NULL,
                                  obrigatoria  BOOLEAN  NOT NULL DEFAULT TRUE,
                                  CONSTRAINT pk_pesquisa_questao PRIMARY KEY (id_pesquisa, id_questao),
                                  CONSTRAINT uq_pesquisa_ordem   UNIQUE (id_pesquisa, ordem),
                                  CONSTRAINT ck_pq_ordem         CHECK (ordem > 0)
);

-- convida(anônimo) e quem já respondeu
CREATE TABLE convite (
                         id_pesquisa  INT NOT NULL REFERENCES pesquisa (id_pesquisa) ON DELETE CASCADE,
                         id_usuario   INT NOT NULL REFERENCES usuario (id_usuario),
                         dt_convite   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         dt_resp      TIMESTAMP,
                         CONSTRAINT pk_convite PRIMARY KEY (id_pesquisa, id_usuario),
                         CONSTRAINT ck_convite_datas CHECK (dt_resp IS NULL OR dt_resp >= dt_convite)
);

-- o que foi respondido
CREATE TABLE submissao (
                           id_sub       UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,  -- UUID aleatório, pela sequência da para a char a ordem das submissões
                           id_pesquisa  INT  NOT NULL REFERENCES pesquisa (id_pesquisa) ON DELETE CASCADE,
                           id_usuario   INT  REFERENCES usuario (id_usuario),
                           id_grupo     INT  NOT NULL REFERENCES grupo (id_grupo),
                           dt_envio     DATE NOT NULL DEFAULT CURRENT_DATE, -- guarda só a data
                           CONSTRAINT uq_submissao_usuario UNIQUE (id_pesquisa, id_usuario) -- identifica quando não é anônimo
);

-- resposta
CREATE TABLE resposta (
                          id_sub          UUID NOT NULL REFERENCES submissao (id_sub) ON DELETE CASCADE,
                          id_questao      INT  NOT NULL REFERENCES questao (id_questao),
                          valor_escala    SMALLINT,
                          id_alternativa  INT,
                          texto           VARCHAR(1000),
                          CONSTRAINT pk_resposta PRIMARY KEY (id_sub, id_questao),
                          CONSTRAINT ck_resposta_escala CHECK (valor_escala BETWEEN 1 AND 5),
                          CONSTRAINT ck_resposta_um_campo CHECK (num_nonnulls(valor_escala, id_alternativa, texto) = 1),
                          CONSTRAINT fk_resposta_alternativa FOREIGN KEY (id_alternativa, id_questao)
                              REFERENCES alternativa (id_alternativa, id_questao)
);

-- Gatilho
CREATE FUNCTION fn_valida_submissao() RETURNS trigger AS $$
DECLARE
p pesquisa%ROWTYPE;
BEGIN
SELECT * INTO p FROM pesquisa WHERE id_pesquisa = NEW.id_pesquisa;

IF p.anonima AND NEW.id_usuario IS NOT NULL THEN
        RAISE EXCEPTION 'Pesquisa % é anônima: a submissão não pode guardar o usuário', p.id_pesquisa;
END IF;
    IF NOT p.anonima AND NEW.id_usuario IS NULL THEN
        RAISE EXCEPTION 'Pesquisa % é identificada: a submissão precisa do usuário', p.id_pesquisa;
END IF;
    IF NEW.dt_envio NOT BETWEEN p.inicio::date AND p.fim::date THEN
        RAISE EXCEPTION 'Data de envio % fora do período da pesquisa % (% a %)',
            NEW.dt_envio, p.id_pesquisa, p.inicio::date, p.fim::date;
END IF;
RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_valida_submissao
    BEFORE INSERT OR UPDATE ON submissao
                         FOR EACH ROW EXECUTE FUNCTION fn_valida_submissao();

